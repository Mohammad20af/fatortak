export const translations = { en: {}, ar };
export function translate(language, key, values = {}) {
  if (key == null) return "";
  const text = translations[language]?.[key] ?? key;
  return typeof text === "string"
    ? text.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match))
    : text;
}
